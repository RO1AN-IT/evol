MEALS = ("завтрак", "обед", "ужин")
DAY_NAMES = ("Пн", "Вт", "Ср", "Чт", "Пт", "Сб", "Вс")


@dataclass(frozen=True)
class Dish:
    index: int
    meal: str
    name: str
    category: str
    kcal: int
    cost: int


def _pack(meal: str, rows: list[tuple[str, str, int, int]]) -> tuple[Dish, ...]:
    return tuple(
        Dish(index, meal, name, category, kcal, cost)
        for index, (name, category, kcal, cost) in enumerate(rows)
    )


